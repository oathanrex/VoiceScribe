/**
 * Returns voice commands filtered by specific language code (e.g. 'hi', 'es', 'fr')
 * or returns all commands if langCode is 'all' or omitted.
 */
export function getVoiceCommandsForLanguage(langCode?: string): VoiceCommandItem[] {
  if (!langCode || langCode === 'all') {
    return VOICE_COMMANDS;
  }
  const prefix = langCode.toLowerCase().split(/[-_]/)[0];
  // Return commands for this language plus universal symbols
  return VOICE_COMMANDS.filter((cmd) => cmd.lang === prefix || cmd.category === 'symbols');
}
